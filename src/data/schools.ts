// Helper functions for Cascading Selectors
export const getAvailableStates = (): string[] => {
  const states = Array.from(new Set(SCHOOLS.map((s) => s.state)));
  return states.sort();
};

export const getCitiesForState = (stateName: string): string[] => {
  const cities = Array.from(
    new Set(SCHOOLS.filter((s) => s.state === stateName).map((s) => s.city))
  );
  return cities.sort();
};

export const getSchoolsForStateAndCity = (stateName: string, cityName: string): School[] => {
  return SCHOOLS.filter((s) => s.state === stateName && s.city === cityName);
};

export const getSchoolById = (id: string): School => {
  return SCHOOLS.find((s) => s.id === id) || SCHOOLS[0];
};
